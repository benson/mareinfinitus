// Demo: 48x72. Roof, three columns of faces (lit edge, mid, shadow), seat.
export function crystalDemo() {
  const p = [];
  for (let c = 0; c < 3; c++) p.push({name: 'roof', x: c * 16, y: 0, shift: c === 2 ? -2 : 0});
  const mids = ['faceA', 'faceB'];
  for (let r = 0; r < 3; r++) {
    p.push({name: 'faceLit', x: 0, y: 8 + r * 16, shift: -1});
    p.push({name: mids[r % 2], x: 16, y: 8 + r * 16, shift: -1});
    p.push({name: mids[(r + 1) % 2], x: 32, y: 8 + r * 16, shift: -3});
  }
  for (let c = 0; c < 3; c++) p.push({name: 'seat', x: c * 16, y: 56, shift: c === 2 ? -3 : -1});
  return p;
}
