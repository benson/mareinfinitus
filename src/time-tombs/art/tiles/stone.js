// Demo: a 96x64 wall. Parapet against sky, cornice, two courses, plinth. Lit
// face for four columns, shadow face (shift -2) for two. A window and an arch
// in the lit face, a stair up to the arch. Variants cycle; nothing repeats
// side by side.
export function stoneDemo() {
  const p = [];
  const lit = (c) => (c >= 4 ? -2 : 0);
  for (let c = 0; c < 6; c++) p.push({name: 'parapet', x: c * 16, y: 0, shift: lit(c)});
  for (let c = 0; c < 6; c++) p.push({name: 'cornice', x: c * 16, y: 8, shift: lit(c)});
  const rows = ['blockA', 'blockB', 'blockC'];
  for (let r = 0; r < 2; r++) for (let c = 0; c < 6; c++) {
    let name = rows[(c + r * 2) % 3];
    if (c === 0) name = 'cornerLit';
    if (c === 5) name = 'cornerShadow';
    p.push({name, x: c * 16, y: 16 + r * 16, shift: lit(c)});
  }
  p.push({name: 'window', x: 48, y: 16, shift: 0});
  p.push({name: 'arch', x: 16, y: 24, shift: 0});
  for (let c = 0; c < 6; c++) p.push({name: 'plinth', x: c * 16, y: 48, shift: lit(c)});
  p.push({name: 'stair', x: 0, y: 40, shift: 0});
  return p;
}
