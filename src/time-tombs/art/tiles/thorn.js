// Demo: 64x88. Three thorns of different heights over a parapet and gate.
// The whole thing sits at shift -3 (black) except tips and lit rims at -2.
export function thornDemo() {
  const p = [];
  p.push({name: 'tip', x: 0, y: 16, shift: -2});
  p.push({name: 'shaft', x: 0, y: 40, shift: -3});
  p.push({name: 'barbL', x: -8, y: 44, shift: -3});
  p.push({name: 'tip', x: 20, y: 0, shift: -2});
  p.push({name: 'shaft', x: 20, y: 24, shift: -3});
  p.push({name: 'shaft', x: 20, y: 40, shift: -3});
  p.push({name: 'barbR', x: 32, y: 30, shift: -3});
  p.push({name: 'tip', x: 44, y: 24, shift: -2});
  p.push({name: 'shaft', x: 44, y: 48, shift: -3});
  for (let c = 0; c < 4; c++) p.push({name: 'parapet', x: c * 16, y: 56, shift: -3});
  p.push({name: 'gate', x: 16, y: 64, shift: -3});
  return p;
}
