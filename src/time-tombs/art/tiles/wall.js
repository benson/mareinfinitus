// Demo: 96x64. Rim, two buttress rows with a ledge between, a mouth cut into
// the foot of a lit strip, talus along the bottom.
export function wallDemo() {
  const p = [];
  // buttress rhythm is irregular: lit, lit, shadow, lit, shadow, shadow
  const litCols = [true, true, false, true, false, false];
  const lit = (c) => (litCols[c] ? 0 : -2);
  const rims = ['rimEdge', 'rimEdgeB', 'rimEdgeC', 'rimEdge', 'rimEdgeC', 'rimEdgeB'];
  for (let c = 0; c < 6; c++) p.push({name: rims[c], x: c * 16, y: 0, shift: lit(c)});
  for (let c = 0; c < 6; c++) p.push({name: litCols[c] ? 'buttressLit' : 'buttressShadow', x: c * 16, y: 8, shift: lit(c)});
  for (let c = 0; c < 6; c++) p.push({name: 'ledge', x: c * 16, y: 24, shift: lit(c)});
  for (let c = 0; c < 6; c++) p.push({name: litCols[c] ? 'buttressLit' : 'buttressShadow', x: c * 16, y: 32, shift: lit(c)});
  p.push({name: 'mouth', x: 32, y: 32, shift: 0});
  for (let c = 0; c < 6; c++) p.push({name: 'talus', x: c * 16, y: 56, shift: lit(c)});
  return p;
}
