// Demo: 64x56. A shard crest, two rows of beds with two chambers, a portal.
export function jadeDemo() {
  const p = [];
  for (let c = 0; c < 4; c++) p.push({name: 'shard', x: c * 16, y: 0, shift: c >= 3 ? -2 : 0});
  const beds = ['bedA', 'bedB'];
  for (let r = 0; r < 2; r++) for (let c = 0; c < 4; c++) p.push({name: beds[(c + r) % 2], x: c * 16, y: 16 + r * 16, shift: c >= 3 ? -2 : 0});
  p.push({name: 'ring', x: 16, y: 16, shift: 0}, {name: 'ring', x: 40, y: 26, shift: 0});
  p.push({name: 'portal', x: 0, y: 32, shift: 0});
  return p;
}
