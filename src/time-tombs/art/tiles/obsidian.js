// Demo: a 32-wide obelisk, 104 tall. Pyramidion, five shaft rows with one
// cartouche row, the door in the bottom lit tile, a plinth.
export function obsidianDemo() {
  const p = [];
  p.push({name: 'capL', x: 0, y: 0, shift: 0}, {name: 'capR', x: 16, y: 0, shift: -3});
  for (let r = 0; r < 5; r++) {
    p.push({name: r === 1 ? 'cartouche' : 'shaftL', x: 0, y: 16 + r * 16, shift: -1});
    p.push({name: 'shaftR', x: 16, y: 16 + r * 16, shift: -3});
  }
  p.push({name: 'door', x: 0, y: 80, shift: -1});
  p.push({name: 'plinth', x: 0, y: 96, shift: -1}, {name: 'plinth', x: 16, y: 96, shift: -3});
  return p;
}
